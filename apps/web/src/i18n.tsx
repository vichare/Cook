export const catalogs: Record<Locale, Catalog> = { en, 'zh-CN': zhCN }
const storageKey = 'cook.locale'

export function normalizeLocale(value: string | null | undefined): Locale | null {
  if (!value) return null
  const normalized = value.toLowerCase()
  return normalized.startsWith('zh') ? 'zh-CN' : normalized.startsWith('en') ? 'en' : null
}

export function detectInitialLocale(
  storage: Pick<Storage, 'getItem'> | null = browserStorage(),
  languages: readonly string[] = typeof navigator === 'undefined' ? [] : navigator.languages,
): Locale {
  const stored = normalizeLocale(storage?.getItem(storageKey))
  if (stored) return stored
  return languages.some((language) => normalizeLocale(language) === 'zh-CN') ? 'zh-CN' : 'en'
}

type Variables = Record<string, string | number>
export type Translate = (key: MessageKey, variables?: Variables) => string

export function translateMessage(locale: Locale, key: MessageKey, variables?: Variables): string {
  const template = catalogs[locale][key]
  return Object.entries(variables ?? {}).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  )
}

export function formatDateValue(locale: Locale, value: string | Date): string {
  return new Intl.DateTimeFormat(locale, { dateStyle: 'medium' }).format(
    typeof value === 'string'
      ? new Date(/^\d{4}-\d{2}-\d{2}$/.test(value) ? `${value}T12:00:00` : value)
      : value,
  )
}

interface I18nValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: Translate
  formatDate: (value: string | Date) => string
  formatDateTime: (value: string | Date) => string
  formatNumber: (value: number) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function LocaleProvider({
  children,
  initialLocale,
  storage,
}: {
  children: React.ReactNode
  initialLocale?: Locale
  storage?: Pick<Storage, 'getItem' | 'setItem'> | null
}) {
  const resolvedStorage = storage === undefined ? browserStorage() : storage
  const [locale, setLocaleState] = useState<Locale>(
    () => initialLocale ?? detectInitialLocale(resolvedStorage),
  )
  const setLocale = useCallback((next: Locale) => {
    try {
      resolvedStorage?.setItem(storageKey, next)
    } catch {
      // The preference still applies for this page when storage is unavailable.
    }
    setLocaleState(next)
  }, [resolvedStorage])
  useEffect(() => {
    document.documentElement.lang = locale
    const skipLink = document.querySelector<HTMLElement>('.skip-link')
    if (skipLink) skipLink.textContent = translateMessage(locale, 'app.skipToContent')
  }, [locale])
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, variables) => translateMessage(locale, key, variables),
    formatDate: (date) => formatDateValue(locale, date),
    formatDateTime: (date) => new Intl.DateTimeFormat(locale, {
      dateStyle: 'medium',
      timeStyle: 'short',
    }).format(typeof date === 'string' ? new Date(date) : date),
    formatNumber: (number) => new Intl.NumberFormat(locale).format(number),
  }), [locale, setLocale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside LocaleProvider')
  return context
}

export const localeStorageKey = storageKey
export type { MessageKey }

function browserStorage(): Storage | null {
  try {
    return globalThis.localStorage ?? null
  } catch {
    return null
  }
}
